/**
 * 护栏：禁止在运行期可能跑在桌面版里的代码中调用 `window.confirm` / `window.alert`。
 *
 * 背景（真实缺陷，2026-10-11 用户报障）：
 *   在桌面版点「清空位置统计」弹错
 *     `[rejection] Command plugin:dialog|confirm not allowed by ACL`
 *
 * 根因链（全部实测，不是推测）：
 *   ① `tauri-plugin-dialog` 启动时注入 `src/init-iife.js`（Rust `lib.rs` 里
 *      `builder.js_init_script(include_str!("init-iife.js"))`），全文只有两行有效代码：
 *        window.alert   = i => invoke("plugin:dialog|message", { message: i.toString() })
 *        window.confirm = async i => invoke("plugin:dialog|confirm", { message: i.toString() })
 *      ⇒ 桌面版里 `window.confirm` **不是**原生同步对话框，而是一次 IPC 调用。
 *   ② 但该插件的 `invoke_handler` 只注册了三条命令：`open` / `save` / `message`
 *      （`tauri-plugin-dialog-2.7.1/src/lib.rs`），**没有 `confirm`**。
 *   ③ `permissions/autogenerated/commands/` 下只有 `message.toml` / `open.toml` / `save.toml`
 *      —— **根本没有 `confirm.toml`** ⇒ 不存在 `allow-confirm` 权限，
 *      `dialog:default` 也只含 `["allow-message","allow-save","allow-open"]`。
 *   ④ 前端把命令名写成全名 `plugin:dialog|confirm`，ACL 查表查不到 ⇒ 拒绝。
 *
 *   ⚠️ 注意 `dialog:default` 的 description 里写着 "All dialog types are enabled"，
 *      这是**上游文档与实现不一致**（它并没包含 ask/confirm）。别信 description，信
 *      permissions 数组和 autogenerated 目录里实际有哪些 toml。
 *
 * 正确做法：用仓库既有的 Radix `components/ui/alert-dialog.tsx`（受控 open/onOpenChange），
 * 两种形态行为一致、不依赖任何 Tauri ACL。参见 custom-song-editor-ui.tsx 与
 * position-heatmap.tsx 的用法。
 */
import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

/** 剥掉 `//` 行注释与 `/* *\/` 块注释，避免注释里提到的名字让断言假通过 */
function stripComments(src: string): string {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map((line) => {
      // 只剥行注释起点之前的 `//`（不处理字符串里的 `//`，本仓无此类干扰）
      const idx = line.indexOf('//')
      return idx >= 0 ? line.slice(0, idx) : line
    })
    .join('\n')
}

/** 递归收集会被打进产物的源码目录 */
function collectSourceFiles(root: string, exts = ['.ts', '.tsx']): string[] {
  const out: string[] = []
  for (const name of readdirSync(root)) {
    const p = join(root, name)
    if (statSync(p).isDirectory()) {
      out.push(...collectSourceFiles(p, exts))
    } else if (exts.some((e) => name.endsWith(e))) {
      out.push(p)
    }
  }
  return out
}

const APP_DIRS = ['app', 'components', 'lib', 'hooks'].map((d) =>
  d.replace(/\\/g, '/'),
)

describe('禁止 window.confirm / window.alert（桌面版会被劫持且无 ACL 权限）', () => {
  it('app/ components/ lib/ hooks/ 下没有任何 window.confirm / window.alert 调用', () => {
    const offenders: string[] = []
    for (const dir of APP_DIRS) {
      for (const file of collectSourceFiles(dir)) {
        const raw = readFileSync(file, 'utf8')
        const src = stripComments(raw)
        const rel = file.replace(/\\/g, '/')
        // 逐行扫描，报告 file:line，便于直接定位
        src.split('\n').forEach((line, i) => {
          // window.confirm( / window.alert( / window['confirm'] 之类
          if (/\bwindow\s*\.\s*(confirm|alert)\b/.test(line)) {
            offenders.push(`${rel}:${i + 1}  ${line.trim()}`)
          }
          if (/\bwindow\s*\[\s*['"](confirm|alert)['"]\s*\]/.test(line)) {
            offenders.push(`${rel}:${i + 1}  ${line.trim()}`)
          }
        })
      }
    }
    expect(
      offenders,
      '桌面版里 tauri-plugin-dialog 会把 window.confirm/alert 改写成 plugin:dialog|* IPC，' +
        '而 confirm 命令没有 ACL 权限（会抛 `not allowed by ACL`）⇒ 请改用 ' +
        'components/ui/alert-dialog.tsx 的受控对话框。\n违规位置：\n' + offenders.join('\n'),
    ).toEqual([])
  })

  it('护栏自身有效性：stripComments 确实剥掉了注释（否则注释里的示例会让断言假通过）', () => {
    const sample = [
      '// window.confirm("注释里的示例，不该被判违规")',
      '/* window.alert("块注释里的") */',
      'const a = 1',
    ].join('\n')
    const stripped = stripComments(sample)
    expect(stripped).not.toContain('window.confirm')
    expect(stripped).not.toContain('window.alert')
    expect(stripped).toContain('const a = 1')

    // 🚨 光断言「剥得掉」不够 —— 若 stripComments 退化成恒等函数，
    //    上面三条**仍然**可能通过（textContent 断言对 window.confirm 失效时不会红）。
    //    必须再加一条**正反对照**：注释里的必须消失，真代码里的必须留下。
    //    这才能咬住「M8 护栏不剥注释」这类变异。
    const withRealCall = [
      '// window.confirm("这只是注释")',
      'window.confirm("这是真调用，必须被检出")',
    ].join('\n')
    const s2 = stripComments(withRealCall)
    expect(s2, '注释里的 window.confirm 必须被剥掉').not.toContain('这只是注释')
    expect(s2, '真代码里的 window.confirm 必须留下（否则护栏形同虚设）').toContain(
      '这是真调用，必须被检出',
    )
  })
})

describe('position-heatmap 的清空确认走受控 AlertDialog', () => {
  const SRC = stripComments(
    readFileSync('components/position-heatmap.tsx', 'utf8'),
  )

  it('使用 AlertDialog 受控组件（open + onOpenChange）', () => {
    expect(SRC).toContain("from '@/components/ui/alert-dialog'")
    expect(SRC).toContain('<AlertDialog')
    // 受控：open 与 onOpenChange 都要有，否则关不掉
    expect(/open=\{confirmOpen\}/.test(SRC), 'AlertDialog 必须受控（open）').toBe(true)
    expect(/onOpenChange=\{setConfirmOpen\}/.test(SRC), 'AlertDialog 必须能关（onOpenChange）').toBe(true)
  })

  it('清空动作绑在 AlertDialogAction 上，主按钮只负责开对话框', () => {
    expect(SRC).toContain('<AlertDialogAction')
    // 主触发按钮只负责开对话框
    expect(SRC).toContain('onClick={() => setConfirmOpen(true)}')
    // handleClear 必须绑在 AlertDialogAction 那个分支里（最后一个 onClick），
    // 即：清空只能经由确认框触发，不能是主按钮的直接 onClick
    const mainBtn = SRC.slice(SRC.indexOf('<Button'), SRC.indexOf('</CardHeader>'))
    expect(/onClick=\{handleClear\}/.test(mainBtn), '主按钮不得直接绑 handleClear').toBe(false)
    const dlg = SRC.slice(SRC.indexOf('<AlertDialog '))
    expect(/onClick=\{handleClear\}/.test(dlg), 'AlertDialogAction 必须绑 handleClear').toBe(true)
  })

  it('清空仍是真的调 clearPositionStats(instrument)', () => {
    expect(SRC).toContain('await clearPositionStats(instrument)')
  })
})
