/**
 * 取某语言的译文表（取不到 ⇒ undefined）。`TRANSLATIONS` 是对象字面量、没有索引签名，
 * 所以这里集中做一次 as 断言，别在每个调用点重复。
 */
function tableOf(language: string | null | undefined): Record<string, string> | undefined {
  const tables = TRANSLATIONS as Record<string, Record<string, string> | undefined>
  return tables[language || 'zh-CN']
}

/**
 * 取译文（本仓**唯一**的查表实现，`createTranslator` 与页面里的 `t` 都走它）。
 *
 * 语义（勿改）：`table?.[key] || key` —— **缺键时返回「键名本身」**，这是个真值，
 * 所以 `t(k) || fallback` 是**假兜底**（详见 `.workbuddy/memory/MEMORY.md` 铁律）。
 * 要判缺键用 `hasTranslation()`，别再用「译文是否等于键名」推断。
 *
 * 语言代码未知时回退 zh-CN；连表都取不到时返回 key。
 */
export function translate(language: string | null | undefined, key: string): string {
  const table = tableOf(language)
  return table?.[key] || key
}

/**
 * 该键在当前语言表里**确有译文**吗？
 *
 * 🚨 为什么不能靠 `t(key) !== key` 推断：万一某条译文恰好写成与键名相同，
 * 就会被误判成缺键而走 fallback。空串译文同样算「没有」（与 `translate()` 的
 * `|| key` 口径一致 —— 空串译文在界面上等于缺键）。
 */
export function hasTranslation(language: string | null | undefined, key: string): boolean {
  const value = tableOf(language)?.[key]
  return typeof value === 'string' && value.length > 0
}

/** 带 `hasKey` 的翻译函数（见 `translateOr`）。 */
export interface Translator {
  (key: string): string
  /** 该键确有译文（比「译文是否等于键名」可靠）。 */
  hasKey(key: string): boolean
}

/** 既可以是 `createTranslator` 的产物，也可以是裸函数（测试替身）。 */
export type TranslatorLike = ((key: string) => string) & {
  hasKey?: (key: string) => boolean
}

/**
 * 生成 `t()` 翻译函数（页面与组件都从这里取）。
 *
 * 历史上 `app/page.tsx` 里还手写过第三份 `TRANSLATIONS[lang]?.[key] || key`
 * （同一段逻辑两处实现，各自腐烂）⇒ 已收敛到 `translate()`。
 */
export function createTranslator(language: string | null | undefined): Translator {
  const t = ((key: string): string => translate(language, key)) as Translator
  t.hasKey = (key: string): boolean => hasTranslation(language, key)
  return t
}

/**
 * `t()` + **真兜底**。要兜底就用它，别再手写 `t(k) || fallback`。
 *
 * 缺键判据优先用 `t.hasKey`（`createTranslator` 产物都带）；传入的是裸函数
 * （测试替身 / 未接上的旧调用方）时退回「译文是否等于键名」的旧判据。
 *
 * 项目里同一段真兜底逻辑曾在 level-info-dialog 与另一个弹窗里各写一遍（写法还对不上），
 * 所以收敛到这里。典型用法：
 *     translateOr(t, `level_desc_${level.id}`, level.description)
 */
export function translateOr(t: TranslatorLike, key: string, fallback: string): string {
  if (typeof t.hasKey === 'function') return t.hasKey(key) ? t(key) : fallback
  const translated = t(key)
  return translated === key ? fallback : translated
}
